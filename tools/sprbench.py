"""Data and layout of the sprite benchmark (src/bench/sprbench.asm).

The font and palette are the SGP benchmark's (tools/sgpbench.py); the
sprite images are generated by the program itself. No ROM data.
"""

from sgpbench import PALETTE, font

DEPTHS = (16, 256)              # colours: 4 and 8 bits a pixel
SIZES = (16, 32, 64, 128)
COUNTS = (32, 16, 8, 4)         # sprites a repetition
SPLITS = ('CPU', 'SGP25', 'SGP50', 'SGP75', 'SGP')
SGP_SHARE = (0, 0.25, 0.5, 0.75, 1)
WINDOW = 240                    # VRTCs a run
RUNS = 2                        # runs a test
CELL = 20


def configs():
    return [(depth, size, count) for depth in DEPTHS for size, count in zip(SIZES, COUNTS)]


def include() -> str:
    data = font()
    lines = ['; Generated by tools/sprbench.py: synthetic data, no ROM.',
             '%define PALETTE16 ' + ','.join(f'{w:#06x}' for w in PALETTE),
             '\t\tjmp\tstart\t\t\t; data first', 'FONT:']
    for i in range(0, len(data), 16):
        lines.append('\t\tdb\t' + ','.join(f'{b:#04x}' for b in data[i:i + 16]))
    return '\n'.join(lines) + '\n'
